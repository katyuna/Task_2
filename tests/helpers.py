"""Вспомогательные функции для тестов."""

from faker import Faker

# Faker — библиотека, которая генерирует правдоподобные случайные данные:
# имена, почты, пароли и т.д. Создаём один объект на весь модуль
# и используем его во всех функциях.
fake = Faker()


def generate_user_data():
    """Возвращает данные для нового пользователя: email, пароль и имя.

    Email должен быть уникальным: сервер не даст зарегистрировать двух
    пользователей с одинаковой почтой. Faker сам по себе может повторить
    почту (имён у него ограниченный набор, а сервер общий для всех),
    поэтому добавляем к логину случайное число,
    например jsmith482913@example.com.
    """
    return {
        "email": f"{fake.user_name()}{fake.random_number(digits=6)}@{fake.free_email_domain()}",
        "password": fake.password(length=10),  # случайный пароль из 10 символов
        "name": fake.first_name(),  # случайное имя, например Anna
    }
